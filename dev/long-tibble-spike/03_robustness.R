suppressMessages({devtools::load_all(quiet = TRUE); library(dplyr); library(tidyr)})
source("dev/long-tibble-spike/img.R")
x <- read_images("demo_images/DIV14Actin-01-Airyscan Processing-02.tif") |> as_long()
ok <- function(label, expr) {
  res <- tryCatch({ v <- expr; if (inherits(v, "tm_img")) "keeps class" else paste("LOST class ->", class(v)[1]) },
                  error = function(e) paste("ERROR:", conditionMessage(e)))
  cat(sprintf("%-42s %s\n", label, res))
}
info <- tibble(channel = unique(x$channel), protein = c("A", "B", "C", "D"))
ok("group_by() + summarise()", (x |> group_by(channel) |> summarise(img = max(img)))$img)
ok("left_join()", left_join(x, info, by = "channel")$img)
ok("inner_join() (img on right side)", inner_join(info, x, by = "channel")$img)
ok("distinct()", distinct(x, channel, .keep_all = TRUE)$img)
ok("rename() / relocate()", relocate(rename(x, image = img), image)$image)
ok("nest() / unnest()", unnest(nest(x, data = -channel), data)$img)
ok("pivot_wider() (img as values)", pivot_wider(select(x, channel, z, img), names_from = z, values_from = img)$`1`)
ok("split() + bind_rows()", bind_rows(split(x, x$channel))$img)
ok("base [ subsetting", x[x$z == 1, ]$img)
ok("base rbind() of tibbles", rbind(x[1:2, ], x[3:4, ])$img)
ok("base rbind() of data.frames", rbind(as.data.frame(x[1:2, ]), as.data.frame(x[3:4, ]))$img)
ok("as.data.frame()", as.data.frame(x)$img)
ok("rev() / head()", head(rev(x$img), 3))
ok("img[2:3] <- img[5:6]", { i <- x$img; i[2:3] <- i[5:6]; i })
ok("c(img, img)", c(x$img[1], x$img[2]))
ok("saveRDS() / readRDS()", { f <- tempfile(); saveRDS(x, f); readRDS(f)$img })
ok("arrange() by img (ordering images)", arrange(x, img)$img)
cat("\nversions: dplyr", format(packageVersion("dplyr")), "| vctrs", format(packageVersion("vctrs")), "| tidyr", format(packageVersion("tidyr")), "\n")
